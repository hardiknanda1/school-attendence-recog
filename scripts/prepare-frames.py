#!/usr/bin/env python3
"""
Prepare the supplied hero animation frames for the web.

Usage:
    python3 scripts/prepare-frames.py <dir-with-extracted-frames>

Input:  the supplied ZIP extracted into a directory of `frame-NNNN.jpg` files
        (1280x720). The export skips some frame numbers; nothing is
        interpolated or generated to fill those gaps.
Output:
  - public/frames/frame-NNNN.webp   same pixels/composition, WebP for delivery
  - public/hero/hero-end.jpg        untouched copy of the final empty-lobby frame (final CTA)
  - lib/frame-manifest.ts           ordered list of source frame numbers

Requires Pillow (`pip install pillow`).
"""

import re
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
FRAME_RE = re.compile(r"^frame-(\d{4})\.jpg$")
QUALITY = 86


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    frames = sorted(
        (int(m.group(1)), p)
        for p in src.iterdir()
        if (m := FRAME_RE.match(p.name))
    )
    if not frames:
        sys.exit(f"No frame-NNNN.jpg files found in {src}")

    sizes = {Image.open(p).size for _, p in frames}
    if len(sizes) != 1:
        sys.exit(f"Frames have inconsistent dimensions: {sizes}")
    width, height = sizes.pop()

    numbers = [n for n, _ in frames]
    missing = [n for n in range(numbers[0], numbers[-1] + 1) if n not in set(numbers)]
    print(f"{len(frames)} frames, {width}x{height}, numbers {numbers[0]}-{numbers[-1]}")
    print(f"Gaps in source numbering (not filled): {missing or 'none'}")

    out_dir = ROOT / "public" / "frames"
    out_dir.mkdir(parents=True, exist_ok=True)
    for old in out_dir.glob("frame-*.webp"):
        old.unlink()
    for n, path in frames:
        Image.open(path).save(out_dir / f"frame-{n:04d}.webp", "WEBP", quality=QUALITY, method=6)

    hero_dir = ROOT / "public" / "hero"
    hero_dir.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(frames[-1][1], hero_dir / "hero-end.jpg")

    rows = ",\n".join(
        "  " + ", ".join(str(n) for n in numbers[i : i + 16]) for i in range(0, len(numbers), 16)
    )
    (ROOT / "lib" / "frame-manifest.ts").write_text(
        "// Generated by scripts/prepare-frames.py — do not edit by hand.\n"
        "// Source frame numbers in playback order. Gaps in the supplied export\n"
        f"// ({', '.join(map(str, missing)) or 'none'}) are intentionally not filled.\n\n"
        f"export const FRAME_WIDTH = {width};\n"
        f"export const FRAME_HEIGHT = {height};\n\n"
        f"export const FRAME_NUMBERS: readonly number[] = [\n{rows},\n];\n\n"
        "export const frameSrc = (n: number) =>\n"
        '  `/frames/frame-${String(n).padStart(4, "0")}.webp`;\n'
    )
    print(f"Wrote {len(frames)} frames to {out_dir.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
